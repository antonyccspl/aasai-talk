import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
// Isolated PostgreSQL runtime, no production credentials or database writes.
// Install: npm install --prefix node_modules/.presence-tests --no-package-lock @electric-sql/pglite
const { PGlite } = await import('../node_modules/.presence-tests/node_modules/@electric-sql/pglite/dist/index.js');
const db = new PGlite();
await db.exec(`
create role anon; create role authenticated; create role service_role;
create table phone_identities(phone text primary key, profile_complete boolean, profile jsonb);
create table phone_profiles(phone text primary key, display_name text, date_of_birth date, gender text, city text, languages text[], interests text[], bio text, avatar_url text);
create table host_applications(phone text primary key, status text, application_profile jsonb);
create table phone_host_presence(host_phone text primary key, last_seen_at timestamptz, accepting_calls boolean default false, show_last_seen boolean default true, accepting_audio_calls boolean default true, accepting_video_calls boolean default true);
create table phone_user_blocks(blocker_phone text, blocked_phone text);
create table call_sessions(id uuid primary key default gen_random_uuid(), caller_phone text, host_phone text, call_type text, status text, room_id text, created_at timestamptz default now(), connected_at timestamptz, started_at timestamptz, ended_at timestamptz, duration_seconds integer default 0);
create function settle_phone_call(uuid,text) returns void language sql as 'select';
`);
const migration = readFileSync(new URL('../supabase/migrations/20261111000300_host_availability_lease.sql', import.meta.url), 'utf8');
await db.exec(migration.replace('create extension if not exists pg_cron;', '').replace(/select cron\.schedule\([^\n]+\);/, ''));
const host = '+919000000001', caller = '+919000000002';
await db.query(`insert into phone_identities values ($1,true,'{}'),($2,true,'{}')`,[host,caller]);
await db.query(`insert into phone_profiles(phone,display_name,date_of_birth,gender) values ($1,'Host','2000-01-01','Female'),($2,'Caller','2000-01-01','Male')`,[host,caller]);
await db.query(`insert into host_applications values ($1,'approved','{"audio":true,"video":true}')`,[host]);
const online = async () => (await db.query('select phone_host_is_online($1) as online',[host])).rows[0].online;
const toggle = value => db.query('select set_phone_host_call_availability($1,$2)',[host,value]);
const start = async () => (await db.query("select start_phone_call($1,$2,'audio') as call",[caller,host])).rows[0].call;
const age = seconds => db.query("update phone_host_presence set last_seen_at = now() - make_interval(secs => $1)",[seconds]);
const directory = async () => (await db.query('select availability from get_public_directory_profiles()')).rows[0].availability;
await toggle(true);
assert.equal(await online(),true);
assert.equal(await directory(),'Available');
await age(90); assert.equal(await online(),true,'background timer delayed over one minute');
await age(240); assert.equal(await online(),true,'four-minute delay remains online');
let call=await start();
await age(301); assert.equal(await online(),false,'closed/offline/shutdown expires by server clock');
await db.exec('select expire_host_presence()');
assert.equal((await db.query('select status from call_sessions where id=$1',[call.id])).rows[0].status,'missed');
assert.equal(await directory(),'Offline');
await assert.rejects(start(),/offline/);
await toggle(true); call=await start();
await toggle(false); assert.equal(await online(),false);
await db.exec('update phone_host_presence set last_seen_at=now()');
assert.equal(await online(),false,'heartbeat cannot undo explicit Offline');
await db.query("select update_phone_call($1,$2,'connected')",[call.id,host]);
assert.equal((await db.query('select status from call_sessions where id=$1',[call.id])).rows[0].status,'missed');
await toggle(true); call=await start();
await db.query("select update_phone_call($1,$2,'connected')",[call.id,host]);
assert.equal((await db.query('select status from call_sessions where id=$1',[call.id])).rows[0].status,'connected');
await db.query("select update_phone_call($1,$2,'ended')",[call.id,host]);
call=await start();
await db.query("update call_sessions set created_at=now()-interval '61 seconds' where id=$1",[call.id]);
await assert.rejects(db.query("select update_phone_call($1,$2,'connected')",[call.id,host]),/expired/);
await db.exec('update host_presence_config set timeout_seconds=600');
await age(400); assert.equal(await online(),true,'timeout is configurable');
await age(601); assert.equal(await online(),false);
await db.exec('set role anon');
await assert.rejects(db.exec('select * from host_presence_config'),/permission denied/);
await assert.rejects(db.query('select set_phone_host_call_availability($1,true)',[host]),/permission denied/);
await db.exec('select * from get_public_directory_profiles()');
await db.exec('reset role');
await db.exec(readFileSync(new URL('../supabase/migrations/20261112000100_foreground_call_receipt.sql', import.meta.url),'utf8'));
await db.exec('select expire_host_presence()');
await toggle(true); call=await start();
assert.equal((await db.query('select acknowledge_phone_host_call($1,$2) as received',[caller,call.id])).rows[0].received,false);
assert.equal((await db.query('select acknowledge_phone_host_call($1,$2) as received',[host,call.id])).rows[0].received,true);
await toggle(false);
assert.equal((await db.query('select acknowledge_phone_host_call($1,$2) as received',[host,call.id])).rows[0].received,false);
await db.exec('set role anon');
await assert.rejects(db.query('select acknowledge_phone_host_call($1,$2)',[host,call.id]),/permission denied/);
await db.close();
console.log('PASS: real PostgreSQL migration, delayed heartbeat, expiry, directory/admission parity, Offline wins, call acceptance, expired invitation, timeout configuration, permissions');
